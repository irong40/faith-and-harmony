#!/usr/bin/env node
/**
 * CRM state monitor.
 *
 * Pulls the live business state from the guarded `crm-snapshot` edge function
 * and writes a plain-language state file the agent workforce reads, plus a JSON
 * copy. Run on a schedule (e.g. Windows Task Scheduler, daily 6:30 AM ET).
 *
 * Needs (from .env, no Supabase service key on disk):
 *   - VITE_SUPABASE_PUBLISHABLE_KEY   (anon key, already in .env)
 *   - CRM_SNAPSHOT_SECRET             (shared guard secret; also set in Supabase fn env)
 *
 * Output dir defaults to the Obsidian vault so every agent picks it up. Override
 * with CRM_SNAPSHOT_OUT.
 *
 * Usage: node scripts/crm-state-snapshot.mjs [--dry-run]
 */
import { readFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SUPABASE_URL = "https://qjpujskwqaehxnqypxzu.supabase.co";
const FN_URL = `${SUPABASE_URL}/functions/v1/crm-snapshot`;
const OUT_DIR = process.env.CRM_SNAPSHOT_OUT
  || "C:/Users/redle.SOULAAN/obsidian-dev/agent-office/crm";
const DRY = process.argv.includes("--dry-run");

function envVal(name) {
  if (process.env[name]) return process.env[name].trim();
  for (const f of [".env", ".env.local"]) {
    if (!existsSync(f)) continue;
    const line = readFileSync(f, "utf8").split(/\r?\n/).find((l) => l.startsWith(`${name}=`));
    if (line) return line.slice(name.length + 1).trim().replace(/^["']|["']$/g, "");
  }
  return null;
}

function fmtAge(mins) {
  if (mins == null) return "never";
  if (mins < 60) return `${mins} min ago`;
  if (mins < 1440) return `${Math.round(mins / 60)} h ago`;
  return `${Math.round(mins / 1440)} d ago`;
}

function buildAlerts(s) {
  const a = [];
  const drip = s.drip?.by_status || {};
  if (s.billing?.delivered_unbilled > 0)
    a.push(`${s.billing.delivered_unbilled} delivered job(s) with **no payment recorded** — possible uninvoiced revenue.`);
  if (s.billing?.payments_total === 0)
    a.push(`**No payments recorded at all** — billing pipeline appears unused.`);
  if (s.quotes?.accepted_without_job > 0)
    a.push(`${s.quotes.accepted_without_job} **accepted quote(s) with no job** created — dropped customer?`);
  if (s.jobs?.stale_scheduled > 0)
    a.push(`${s.jobs.stale_scheduled} job(s) **scheduled in the past** still sitting in 'scheduled' — groom the board.`);
  if ((drip.skipped || 0) > 0 && !s.drip?.last_sent)
    a.push(`Drip: ${drip.skipped} email(s) failed and **0 ever sent** — check Resend domain verification.`);
  if (s.drip?.due_now_pending > 0)
    a.push(`Drip: ${s.drip.due_now_pending} email(s) due and unsent — is the drip cron running?`);
  if (s.leads?.new_7d === 0)
    a.push(`No new leads in the last 7 days.`);
  if (s.automation?.n8n_minutes_since_ping != null && s.automation.n8n_minutes_since_ping > 20)
    a.push(`n8n heartbeat stale (${fmtAge(s.automation.n8n_minutes_since_ping)}) — automations may be down.`);
  return a;
}

function obj(o) {
  return Object.keys(o || {}).length
    ? Object.entries(o).map(([k, v]) => `${k}: ${v}`).join(" · ")
    : "—";
}

function toMarkdown(s) {
  const alerts = buildAlerts(s);
  return `# CRM Business State

> Auto-generated by \`scripts/crm-state-snapshot.mjs\`. Source of truth = live Supabase CRM.
> Generated: ${s.generated_at}

## ⚠️ Alerts (${alerts.length})
${alerts.length ? alerts.map((a) => `- ${a}`).join("\n") : "- None"}

## Jobs (${s.jobs?.total ?? "?"})
- By status: ${obj(s.jobs?.by_status)}
- Stale scheduled (date in past): **${s.jobs?.stale_scheduled ?? "?"}**
- Uploaded, awaiting QA: ${s.jobs?.uploaded_awaiting_qa ?? "?"}

## Leads (${s.leads?.total ?? "?"})
- By status: ${obj(s.leads?.by_status)}
- New in last 7 days: ${s.leads?.new_7d ?? "?"}

## Quotes
- By status: ${obj(s.quotes?.by_status)}
- Accepted but no job: **${s.quotes?.accepted_without_job ?? "?"}**

## Billing
- Payments recorded: ${s.billing?.payments_total ?? "?"} (pending: ${s.billing?.payments_pending ?? "?"}, $${s.billing?.pending_amount ?? 0})
- Delivered but unbilled: **${s.billing?.delivered_unbilled ?? "?"}**

## Drip email
- By status: ${obj(s.drip?.by_status)}
- Due now (pending): ${s.drip?.due_now_pending ?? "?"}
- Last sent: ${s.drip?.last_sent ?? "never"}

## Automation
- n8n last heartbeat: ${fmtAge(s.automation?.n8n_minutes_since_ping)} (${s.automation?.n8n_last_ping ?? "—"})
`;
}

async function main() {
  const anon = envVal("VITE_SUPABASE_PUBLISHABLE_KEY");
  const secret = envVal("CRM_SNAPSHOT_SECRET");
  if (!anon) throw new Error("VITE_SUPABASE_PUBLISHABLE_KEY missing from env/.env");
  if (!secret) throw new Error("CRM_SNAPSHOT_SECRET missing from env/.env");

  const res = await fetch(FN_URL, {
    method: "POST",
    headers: {
      apikey: anon,
      Authorization: `Bearer ${anon}`,
      "x-snapshot-secret": secret,
      "Content-Type": "application/json",
    },
  });
  if (!res.ok) throw new Error(`crm-snapshot returned ${res.status}: ${await res.text()}`);
  const snapshot = await res.json();
  const md = toMarkdown(snapshot);

  if (DRY) {
    console.log(md);
    return;
  }

  if (!existsSync(OUT_DIR)) mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(join(OUT_DIR, "business-state.md"), md, "utf8");
  writeFileSync(join(OUT_DIR, "business-state.json"), JSON.stringify(snapshot, null, 2), "utf8");
  console.log(`Wrote business-state.{md,json} to ${OUT_DIR}`);
  const alerts = buildAlerts(snapshot);
  if (alerts.length) console.log(`${alerts.length} alert(s):\n- ${alerts.join("\n- ")}`);
}

main().catch((e) => {
  console.error("crm-state-snapshot failed:", e.message);
  process.exit(1);
});
